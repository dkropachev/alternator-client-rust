    printf '%s\n' \
        '#!/usr/bin/env bash' \
        'set -euo pipefail' \
        'printf '\''%s\n'\'' "${0##*/}" >>"${FORBIDDEN_CALLS:?}"' \
        'exit 97' >"$fake_bin/$command"
    chmod 755 "$fake_bin/$command"
done

expect_validation_guard() {
    local label=$1
    local expected_diagnostic=$2
    local script=$3
    shift 3
    local marker=$test_dir/$label-forbidden-calls
    local output_file=$test_dir/$label-output

    set +e
    PATH="$fake_bin:$PATH" \
        FORBIDDEN_CALLS="$marker" \
        CARGO_REGISTRY_TOKEN= \
        GITHUB_REPOSITORY=scylladb/alternator-client-rust \
        GH_TOKEN= \
        RELEASE_APP_TOKEN= \
        "$script" "$@" >"$output_file" 2>&1
    last_status=$?
    set -e
    last_output=$(<"$output_file")
    [[ "$last_status" -eq 1 ]] || {
        echo "$label: expected mode rejection status 1, got $last_status" >&2
        echo "$last_output" >&2
        exit 1
    }
    [[ "$last_output" == *"$expected_diagnostic"* ]] || {
        echo "$label: missing diagnostic: $expected_diagnostic" >&2
        echo "$last_output" >&2
        exit 1
    }
    [[ ! -e "$marker" ]] || {
        echo "$label: validation artifact reached a credential, network, or mutation command" >&2
        cat "$marker" >&2
        exit 1
    }
    test_count=$((test_count + 1))
}

expect_validation_guard publish_rejects_validation \
    'publish requires release_mode=release' "$publisher" \
    validate "$test_dir/nonexistent-package" "$version" "$validation_candidate" "$commit" "$validation_dir"
