    "manifest candidate ID $release_candidate does not match expected ID $other_release_candidate" \
    "$release_dir" "$test_dir/extract" release "$version" "$other_release_candidate" "$commit"
expect_verify_failure wrong_expected_commit \
    "manifest commit $commit does not match expected commit $other_commit" \
    "$release_dir" "$test_dir/extract" release "$version" "$release_candidate" "$other_commit"

expect_verify_failure release_artifact_as_validation \
    'manifest mode release does not match expected mode validate' \
    "$release_dir" "$test_dir/extract" validate "$version" "$validation_candidate" "$commit"
expect_verify_failure validation_artifact_as_release \
    'manifest mode validate does not match expected mode release' \
    "$validation_dir" "$test_dir/extract" release "$version" "$release_candidate" "$commit"
expect_verify_failure wrong_validation_candidate \
    "manifest candidate ID $validation_candidate does not match expected ID $other_validation_candidate" \
    "$validation_dir" "$test_dir/extract" validate "$version" "$other_validation_candidate" "$commit"

bad_release_rc_dir=$test_dir/bad-release-rc
cp -R "$release_dir" "$bad_release_rc_dir"
