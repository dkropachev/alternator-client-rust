mkdir "$test_dir/extract"

test_count=0
last_status=0
last_output=

run_verifier() {
    local output_file=$test_dir/verifier-output

    set +e
    "$verifier" "$@" >"$output_file" 2>&1
    last_status=$?
    set -e
    last_output=$(<"$output_file")
}

expect_verify_success() {
    local label=$1
    shift

    run_verifier "$@"
    [[ "$last_status" -eq 0 ]] || {
        echo "$label: expected verification success, got status $last_status" >&2
        echo "$last_output" >&2
        exit 1
    }
    test_count=$((test_count + 1))
}

expect_verify_failure() {
    local label=$1
    local diagnostic=$2
    shift 2

    run_verifier "$@"
    [[ "$last_status" -ne 0 ]] || {
        echo "$label: expected verification failure" >&2
        echo "$last_output" >&2
        exit 1
    }
    [[ "$last_output" == *"$diagnostic"* ]] || {
        echo "$label: missing diagnostic: $diagnostic" >&2
        echo "$last_output" >&2
        exit 1
    }
    test_count=$((test_count + 1))
}

expect_verify_success valid_release \
    "$release_dir" "$test_dir/extract" release "$version" "$release_candidate" "$commit"
expect_verify_success valid_validation \
    "$validation_dir" "$test_dir/extract" validate "$version" "$validation_candidate" "$commit"

