expect_evidence() {
    local label=$1
    local release_mode=$2
    local candidate_id=$3
    local attestation_result=$4
    local expected_passed=$5
    local output_file=$test_dir/$label.json
    local command_output=$test_dir/$label-output

    set +e
    GITHUB_REPOSITORY=scylladb/alternator-client-rust \
        GITHUB_RUN_ID=$run_id \
        GITHUB_RUN_ATTEMPT=2 \
        GH_TOKEN=test-token \
        PORTABLE_RESULT=success \
        STATIC_RESULT=success \
        SCYLLA_RESULT=success \
        ATTESTATION_RESULT="$attestation_result" \
        PATH="$evidence_bin:$PATH" \
        "$evidence_generator" \
        "$release_mode" "$version" "$candidate_id" "$commit" "$crate_sha" "$output_file" \
        >"$command_output" 2>&1
    last_status=$?
    set -e
    last_output=$(<"$command_output")
    [[ "$last_status" -eq 0 ]] || {
        echo "$label: evidence generation failed with status $last_status" >&2
        echo "$last_output" >&2
        exit 1
    }
    jq -e \
        --arg mode "$release_mode" \
        --arg candidate "$candidate_id" \
        --arg attestation "$attestation_result" \
        --argjson expected_passed "$expected_passed" '
        .schema_version == 2 and
        .release_mode == $mode and
        .candidate_id == $candidate and
        .aggregate_results.attestation == $attestation and
        .aggregate_results.portable == "success" and
        .aggregate_results.static_release == "success" and
        .aggregate_results.scylla == "success" and
        .all_required_gates_passed == $expected_passed and
        (.jobs | length == 1) and
        (if $mode == "release"
         then .rc_tag == $candidate
         else .rc_tag == null
         end)
    ' "$output_file" >/dev/null || {
        echo "$label: generated evidence did not match its mode/gate contract" >&2
        jq . "$output_file" >&2
        exit 1
    }
    test_count=$((test_count + 1))
}

expect_evidence release_attestation_success \
    release "$release_candidate" success true
expect_evidence validation_attestation_skipped \
    validate "$validation_candidate" skipped true
expect_evidence validation_attestation_success \
    validate "$validation_candidate" success false
expect_evidence release_attestation_skipped \
    release "$release_candidate" skipped false

fake_bin=$test_dir/forbidden-bin
mkdir "$fake_bin"
