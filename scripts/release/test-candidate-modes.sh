    echo "usage: $0" >&2
    exit 2
}

for command in jq shasum tar; do
    command -v "$command" >/dev/null || {
        echo "$command is required to run candidate-mode tests" >&2
        exit 1
    }
done

script_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
verifier=$script_dir/verify-candidate.sh
publisher=$script_dir/publish-and-verify.sh
finalizer=$script_dir/finalize-release.sh
evidence_generator=$script_dir/create-evidence.sh
test_dir=$(mktemp -d)
trap 'rm -rf -- "$test_dir"' EXIT

version=9.8.7
other_version=9.8.8
commit=0123456789abcdef0123456789abcdef01234567
other_commit=abcdef0123456789abcdef0123456789abcdef01
run_id=24680
release_candidate="v$version-rc.3"
other_release_candidate="v$version-rc.4"
validation_candidate="validation-$run_id"
other_validation_candidate=validation-24681
rust_pin=1.94.1
rustdoc_pin=nightly-2026-06-23
ccm_pin=f9e8f8c221f76251318c61ba8a0ce6acec860f6d
scylla_versions=$(bash "$script_dir/release-policy.sh" scylla-versions)
