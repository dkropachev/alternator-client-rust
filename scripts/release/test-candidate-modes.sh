    'finalization requires release_mode=release' "$finalizer" \
    validate "$version" "$validation_candidate" "$commit" "$validation_dir" "$test_dir/nonexistent-evidence"
expect_validation_guard publish_rejects_relabelled_validation_artifact \
    'manifest mode validate does not match expected mode release' "$publisher" \
    release "$test_dir/nonexistent-package" "$version" "$release_candidate" "$commit" "$validation_dir"
expect_validation_guard finalize_rejects_relabelled_validation_artifact \
    'manifest mode validate does not match expected mode release' "$finalizer" \
    release "$version" "$release_candidate" "$commit" "$validation_dir" "$test_dir/nonexistent-evidence"

echo "$test_count candidate-mode release tests passed"
