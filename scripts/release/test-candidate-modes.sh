    echo "missing_all_identity_arguments: expected usage status 2, got $last_status" >&2
    exit 1
}
expect_verify_failure missing_expected_commit 'usage:' \
    "$release_dir" "$test_dir/extract" release "$version" "$release_candidate"
[[ "$last_status" -eq 2 ]] || {
    echo "missing_expected_commit: expected usage status 2, got $last_status" >&2
    exit 1
}
expect_verify_failure wrong_expected_mode 'invalid expected release mode: preview' \
    "$release_dir" "$test_dir/extract" preview "$version" "$release_candidate" "$commit"
