sha256() {
    shasum -a 256 "$1" | awk '{ print $1 }'
}

refresh_checksums() {
    local candidate_dir=$1
    local crate_file
    local sbom_file

    crate_file=$(jq -er '.crate.file' "$candidate_dir/release-manifest.json")
    sbom_file=$(jq -er '.sbom.file' "$candidate_dir/release-manifest.json")
    (
        cd "$candidate_dir"
        shasum -a 256 "$crate_file" "$sbom_file" release-manifest.json >SHA256SUMS
    )
}

write_candidate() {
    local candidate_dir=$1
    local release_mode=$2
    local candidate_id=$3
    local workflow_run_id=$4
    local rc_tag_json=$5
    local stage=$test_dir/stage-${candidate_dir##*/}
    local root=alternator-client-$version
    local package_dir=$stage/$root
    local crate_file=alternator-client-$version.crate
    local sbom_file=alternator-client-$version.cdx.json
    local crate_sha
    local sbom_sha
    local cargo_lock_sha
    local changelog_sha

    mkdir -p "$candidate_dir" "$package_dir"
    printf '%s\n' \
        '[package]' \
        'name = "alternator-client"' \
        "version = \"$version\"" \
        'edition = "2021"' >"$package_dir/Cargo.toml"
    printf '%s\n' \
        '# This file is automatically @generated by Cargo.' \
        'version = 3' \
        '' \
        '[[package]]' \
        'name = "alternator-client"' \
        "version = \"$version\"" >"$package_dir/Cargo.lock"
    printf '# Changelog\n\n## [%s] - 2026-10-02\n\nSynthetic test release.\n' \
        "$version" >"$package_dir/CHANGELOG.md"
    jq -n --arg commit "$commit" \
        '{git: {sha1: $commit}, path_in_vcs: ""}' >"$package_dir/.cargo_vcs_info.json"

    tar -czf "$candidate_dir/$crate_file" -C "$stage" "$root"
    printf '%s\n' \
        '{"bomFormat":"CycloneDX","specVersion":"1.6","components":[]}' \
        >"$candidate_dir/$sbom_file"

    crate_sha=$(sha256 "$candidate_dir/$crate_file")
    sbom_sha=$(sha256 "$candidate_dir/$sbom_file")
    cargo_lock_sha=$(sha256 "$package_dir/Cargo.lock")
    changelog_sha=$(sha256 "$package_dir/CHANGELOG.md")
    jq -n \
        --arg release_mode "$release_mode" \
        --arg candidate_id "$candidate_id" \
        --arg version "$version" \
        --arg crate_file "$crate_file" \
        --arg crate_sha "$crate_sha" \
        --arg sbom_file "$sbom_file" \
        --arg sbom_sha "$sbom_sha" \
        --arg commit "$commit" \
        --arg workflow_run_id "$workflow_run_id" \
        --arg rust_pin "$rust_pin" \
        --arg rustdoc_pin "$rustdoc_pin" \
        --arg ccm_pin "$ccm_pin" \
        --arg cargo_lock_sha "$cargo_lock_sha" \
        --arg changelog_sha "$changelog_sha" \
        --argjson rc_tag "$rc_tag_json" \
        --argjson scylla_versions "$scylla_versions" '
        {
            schema_version: 2,
            release_mode: $release_mode,
            candidate_id: $candidate_id,
            crate: {
                name: "alternator-client",
                library_name: "alternator_driver",
                version: $version,
                file: $crate_file,
                sha256: $crate_sha
            },
            rc_tag: $rc_tag,
            commit_sha: $commit,
            workflow_run_id: $workflow_run_id,
            toolchains: {
                rust: {pin: $rust_pin, actual: "rustc synthetic-test"},
                rustdoc: {pin: $rustdoc_pin, actual: "rustdoc synthetic-test"}
            },
            ccm_commit: $ccm_pin,
            scylla_versions: $scylla_versions,
            cargo_lock_sha256: $cargo_lock_sha,
            changelog_sha256: $changelog_sha,
            source_date_epoch: "1790899200",
            sbom: {file: $sbom_file, sha256: $sbom_sha}
        }
    ' >"$candidate_dir/release-manifest.json"
    refresh_checksums "$candidate_dir"
}

release_dir=$test_dir/release
validation_dir=$test_dir/validation
release_rc_json=$(jq -cn --arg rc "$release_candidate" '$rc')
write_candidate "$release_dir" release "$release_candidate" "$run_id" "$release_rc_json"
